"""Does the fitted model misprice a fresh tyre? A fourth candidate for Result 3.

The sharpest objection raised against Result 3 from outside: a linear
degradation slope carries no one-off gain at a stop, so an optimiser built on it
would always recommend stopping later than a pit wall that is buying an
immediate jump in pace. Pricing that jump in, the argument goes, would close the
gap.

The claim is testable without building anything, because the shape a linear fit
misses shows up in its own residuals. For every circuit this fits the published
model and averages the residual at each tyre age. A fit forces its residuals to
average zero overall; what matters is the profile. Residuals that are
systematically NEGATIVE at low tyre age mean laps faster than the model says,
which is the fresh-tyre bonus the objection predicts. Residuals that are
POSITIVE there mean the opposite.

The out-lap is already outside the modelling frame, so this measures the first
flying laps on a new set, which is what a pit wall is actually buying.

The answer has the wrong sign, which is why this script exists and is reported:
new tyres in this data are slower than modelled for the first two laps, not
faster. Pricing the real effect in pushes the optimiser LATER, widening the gap
rather than closing it.

Usage:

    python scripts/run_fresh_tyre.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.degradation.dataset import (  # noqa: E402
    build_modelling_frame,
    circuits_with_laps,
    load_circuit_laps,
)
from src.degradation.model import fit_circuit, predict_shape  # noqa: E402
from src.degradation.validation import leave_one_race_out, mean_rmse  # noqa: E402
from src.ingestion.config import DERIVED_DIR, REPORTS_DIR  # noqa: E402

OUT_CSV = DERIVED_DIR / "f1" / "fresh_tyre.csv"
OUT_PROFILE = DERIVED_DIR / "f1" / "fresh_tyre_profile.csv"
OUT_MD = REPORTS_DIR / "f1" / "fresh_tyre.md"

DEGREES = (1, 2)
#: Ages reported in the pooled profile. Past this the stint is no longer "fresh"
#: by any reading and the profile is just the degradation curve.
MAX_AGE = 12
#: "Fresh" for the per-circuit summary.
FRESH_AGES = (1, 2, 3)
#: A circuit-age cell below this many laps is not averaged.
MIN_LAPS = 20


def measure() -> tuple[pd.DataFrame, pd.DataFrame]:
    per_age: dict[int, list[float]] = {a: [] for a in range(1, MAX_AGE + 1)}
    rows = []
    for circuit in circuits_with_laps():
        try:
            laps = load_circuit_laps(circuit)
        except ValueError:
            continue
        frame, _ = build_modelling_frame(laps, circuit)
        if frame.empty:
            continue
        cv = {d: leave_one_race_out(frame, circuit, degree=d) for d in DEGREES}
        usable = {d: f for d, f in cv.items() if f}
        if not usable:
            continue
        degree = min(usable, key=lambda d: mean_rmse(usable[d]))

        fit = fit_circuit(frame, circuit, degree=degree)
        pred = predict_shape(fit, frame) + frame["driver_race"].map(fit.fixed_effects)
        resid = frame["lap_time_s"] - pred
        keep = resid.notna()
        age = frame.loc[keep, "TyreLife"].astype(int)
        r = resid[keep]

        fresh_mask = age.isin(FRESH_AGES)
        if not fresh_mask.any() or not (~fresh_mask).any():
            continue
        fresh = float(r[fresh_mask].mean())
        worn = float(r[~fresh_mask].mean())
        rows.append(
            {
                "circuit": circuit,
                "degree": degree,
                "resid_fresh_s": fresh,
                "resid_worn_s": worn,
                # Positive would mean fresh laps come in FASTER than modelled,
                # which is the bonus the objection predicts.
                "bonus_s": worn - fresh,
                "n_fresh_laps": int(fresh_mask.sum()),
            }
        )
        for a in range(1, MAX_AGE + 1):
            cell = r[age == a]
            if len(cell) >= MIN_LAPS:
                per_age[a].append(float(cell.mean()))
        print(f"  {circuit:16s} fresh {fresh:+.4f}s  worn {worn:+.4f}s", flush=True)

    profile = pd.DataFrame(
        [
            {"tyre_age": a, "mean_resid_s": float(np.mean(v)), "circuits": len(v)}
            for a, v in per_age.items()
            if v
        ]
    )
    return pd.DataFrame(rows).sort_values("bonus_s", ascending=False), profile


def write_report(table: pd.DataFrame, profile: pd.DataFrame) -> Path:
    bonus = table["bonus_s"].dropna()
    faster = int((bonus > 0).sum())
    first = profile.sort_values("tyre_age").iloc[0]
    lines = [
        "<!-- GENERATED by scripts/run_fresh_tyre.py — do not edit by hand."
        " Every number here is read from a committed artifact; change the data or"
        " the generator, not this file. -->",
        "",
        "# Is a fresh tyre worth more than the slope says?",
        "",
        "The objection this answers: a linear degradation slope has no one-off"
        " gain at a stop, so an optimiser built on it should always stop later"
        " than a pit wall buying an immediate jump in pace, and pricing that"
        " jump in would close the gap in Result 3.",
        "",
        "A fit forces its residuals to average zero overall, so the profile is"
        " what carries the answer. **Negative means laps faster than the model"
        " says.**",
        "",
        "| tyre age | mean residual (s) | circuits |",
        "|---|---|---|",
    ]
    for _, r in profile.sort_values("tyre_age").iterrows():
        lines.append(
            f"| {int(r['tyre_age'])} | {r['mean_resid_s']:+.4f} | {int(r['circuits'])} |"
        )
    lines += [
        "",
        f"The first measured age carries **{first['mean_resid_s']:+.4f}s** — laps"
        " on a new set are *slower* than the fit expects, not faster, and the"
        " sign only turns over once the set is several laps old. That is tyre"
        " warm-up, and it is the opposite of the effect the objection predicts.",
        "",
        f"Per circuit, fresh laps come in faster than modelled at only"
        f" **{faster} of {len(bonus)}** circuits, median"
        f" **{bonus.median():+.4f}s**.",
        "",
        "| circuit | degree | fresh (s) | worn (s) | bonus (s) |",
        "|---|---|---|---|---|",
    ]
    for _, r in table.iterrows():
        lines.append(
            f"| {r['circuit']} | {int(r['degree'])} | {r['resid_fresh_s']:+.4f} | "
            f"{r['resid_worn_s']:+.4f} | {r['bonus_s']:+.4f} |"
        )
    lines += [
        "",
        "## What this does to Result 3",
        "",
        "It makes the gap harder to explain, not easier. The optimiser prices a"
        " stop as an instant return to the slope's intercept. Real new tyres"
        " need a lap or two to come up to temperature, so the engine is already"
        " **over**stating what a stop buys. Correcting it would push the"
        " recommended lap later still and widen the disagreement. This is the"
        " fourth candidate explanation tested here and the fourth to fail.",
        "",
    ]
    OUT_MD.parent.mkdir(parents=True, exist_ok=True)
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    return OUT_MD


def main() -> int:
    print("measuring the residual profile by tyre age")
    table, profile = measure()
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(OUT_CSV, index=False)
    profile.to_csv(OUT_PROFILE, index=False)
    print(f"\nwrote {OUT_CSV}")
    print(f"wrote {OUT_PROFILE}")
    print(f"wrote {write_report(table, profile)}")
    print()
    print(profile.sort_values("tyre_age").to_string(index=False))
    bonus = table["bonus_s"].dropna()
    print(f"\nfresh faster than modelled at {int((bonus > 0).sum())} of {len(bonus)} circuits")
    return 0


if __name__ == "__main__":
    sys.exit(main())
