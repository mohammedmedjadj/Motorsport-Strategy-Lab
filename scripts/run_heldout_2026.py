"""The 2026 races already ingested, replayed with the frozen pre-2026 models.

Twelve 2026 Grands Prix were ingested before the prospective test was frozen
and are held out of every model and audit in the paper. The committed audit was
never run on them; their laps did enter an earlier version of the noise ceiling,
before it was restricted to the 2022--2025 seasons. They are replayed here with
the same code as the design checks (``scripts/run_audit_design_checks.py``) and
the committed circuit models, which were fitted on the cars of the previous
rules and are not refitted. This is out of sample but **not** pre-registered:
the prospective test (``paper/prospective_protocol.md``) covers the races from
the 2026 São Paulo Grand Prix onward.

Writes ``data/derived/f1/heldout_2026.csv``, ``..._summary.json`` and
``reports/f1/heldout_2026.md``.

    python scripts/run_heldout_2026.py
"""

from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
sys.path.insert(0, str(REPO))

from run_audit_design_checks import add_ratio, build, race_ci  # noqa: E402
from src.ingestion.config import F1_DERIVED_DIR, F1_REPORTS_DIR  # noqa: E402
from src.simulator.artifacts import load_circuit_models  # noqa: E402

SEASON = 2026
OUT_CSV = F1_DERIVED_DIR / "heldout_2026.csv"
OUT_JSON = F1_DERIVED_DIR / "heldout_2026_summary.json"
OUT_MD = F1_REPORTS_DIR / "heldout_2026.md"
BOOT_SEED = 20261111
HARDNESS = {"SOFT": 0, "MEDIUM": 1, "HARD": 2}


def races() -> list[tuple[int, str]]:
    models = load_circuit_models()
    found = sorted(p.stem[len(f"laps_{SEASON}_"):] for p in F1_DERIVED_DIR.glob(f"laps_{SEASON}_*.csv"))
    return [(SEASON, c) for c in found if c in models]


def summarise(frame: pd.DataFrame, n_ingested: int) -> dict:
    rng = np.random.default_rng(BOOT_SEED)
    out = {"n_ingested": n_ingested, "n_races": int(frame[["season", "circuit"]].drop_duplicates().shape[0])}
    for name, lookback, top in (("top5_five", 5, True), ("all_fifteen", 15, False)):
        part = frame[(frame["lookback"] == lookback) & (frame["top"] if top else True)]
        one = part[part["n_stops"] == 1]
        out[name] = {
            "n": int(len(part)), "races": int(part["circuit"].nunique()),
            "median": float(part["delta_laps"].median()),
            "ci": list(race_ci(part, "delta_laps", rng)),
            "one_n": int(len(one)),
            "one_median": float(one["delta_laps"].median()) if len(one) else float("nan"),
        }
    base = frame[(frame["lookback"] == 5) & frame["top"]]
    usable = base.dropna(subset=["implied_ratio", "fitted_ratio"])
    usable = usable[usable["ratio_class"] != "same compound"]
    harder = usable["target"].map(HARDNESS) > usable["compound"].map(HARDNESS)
    out["implied"] = {
        "n": int(len(usable)),
        "median": float(usable["implied_ratio"].median()) if len(usable) else float("nan"),
        "ci": list(race_ci(usable, "implied_ratio", rng)) if len(usable) else [float("nan")] * 2,
        "to_harder_n": int(harder.sum()),
        "to_harder": float(usable.loc[harder, "implied_ratio"].median()) if harder.any() else float("nan"),
        "to_softer_n": int((~harder).sum()),
        "to_softer": float(usable.loc[~harder, "implied_ratio"].median()) if (~harder).any() else float("nan"),
    }
    return out


def main() -> int:
    warnings.filterwarnings("ignore")
    todo = races()
    frame = add_ratio(build(todo))
    frame.to_csv(OUT_CSV, index=False)
    s = summarise(frame, len(list(F1_DERIVED_DIR.glob(f"laps_{SEASON}_*.csv"))))
    s["skipped_no_model"] = sorted(
        p.stem[len(f"laps_{SEASON}_"):] for p in F1_DERIVED_DIR.glob(f"laps_{SEASON}_*.csv")
        if (SEASON, p.stem[len(f"laps_{SEASON}_"):]) not in todo)
    s["no_replayable_decision"] = sorted(c for _, c in todo if c not in set(frame["circuit"]))

    def clean(v):
        if isinstance(v, dict):
            return {k: clean(x) for k, x in v.items()}
        if isinstance(v, list):
            return [clean(x) for x in v]
        return round(v, 6) if isinstance(v, float) else v

    OUT_JSON.write_text(json.dumps(clean(s), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    a, b, i = s["top5_five"], s["all_fifteen"], s["implied"]
    md = "\n".join([
        "# The 2026 races already ingested, replayed out of sample (not pre-registered)", "",
        "Generated by `scripts/run_heldout_2026.py`. Frozen pre-2026 models, not refitted.", "",
        f"- {s['n_races']} of the {s['n_ingested']} ingested races replayed; skipped for want "
        f"of a fitted circuit model: {', '.join(s['skipped_no_model']) or 'none'}; with no "
        f"replayable decision (wet tyres or an early stop): "
        f"{', '.join(s['no_replayable_decision']) or 'none'}.",
        f"- Committed replay, top five, five laps ahead: median {a['median']:+.1f} laps "
        f"[{a['ci'][0]:+.1f}, {a['ci'][1]:+.1f}] over {a['n']} decisions; one-stop "
        f"{a['one_median']:+.1f} over {a['one_n']}.",
        f"- Whole field, fifteen laps ahead: median {b['median']:+.1f} [{b['ci'][0]:+.1f}, "
        f"{b['ci'][1]:+.1f}] over {b['n']} decisions.",
        f"- Implied ratio: median {i['median']:.2f} [{i['ci'][0]:.2f}, {i['ci'][1]:.2f}] over "
        f"{i['n']} decisions; to a harder compound {i['to_harder']:.2f} ({i['to_harder_n']}), to a "
        f"softer one {i['to_softer']:.2f} ({i['to_softer_n']}).", ""])
    OUT_MD.write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
