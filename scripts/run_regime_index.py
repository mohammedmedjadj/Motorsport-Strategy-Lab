"""Where the spread of the regime index comes from.

Result 2 ranks race-seasons by pit loss and by net slope and reports each one's
AUC against the regime the exact multi-stop optimiser chose. An AUC is
invariant to monotone transformations of one variable, but it is not invariant
to how widely each variable happens to vary in the sample: pit loss runs from a
few seconds to several minutes across these four championships, while the
slope varies far less. The regime is, up to the dynamic program's details, a
known function of the two through the closed-form comparison
``beta * n^2 / 2`` against ``pi``. So the defensible question is how much of
the spread of that comparison, in this sample, comes from each term.

The index is ``I = log(beta) + 2 log(n) - log(pi) - log(2)``, with ``n`` the
fuel range in laps, defined where the net slope is positive. Its variance
splits exactly into ``cov(term, I) / var(I)`` for the three terms, which sum
to one; a term that varies a lot, or that covaries with the others in the same
direction, takes a large share. Because spread far from the boundary cannot
change a verdict, each term is also dropped from the index in turn and the
index's AUC recomputed. The index's own AUC against the optimiser's
regime is reported as a check that the closed form describes the verdict.

This describes these four championships, not a law of motorsport: a sample in
which pit loss varied less would give the slope a larger share.

Writes ``data/derived/cross_series/regime_index_summary.json`` and
``reports/cross_series/regime_index.md``.

    python scripts/run_regime_index.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts"))

from run_regime_decomposition import auc  # noqa: E402
from src.ingestion.config import DERIVED_DIR, ENDURANCE_DERIVED_DIR, REPORTS_DIR  # noqa: E402

PLANS = ENDURANCE_DERIVED_DIR / "multistop_plans.csv"
OUT_JSON = DERIVED_DIR / "cross_series" / "regime_index_summary.json"
OUT_MD = REPORTS_DIR / "cross_series" / "regime_index.md"
SEED = 20261108
DRAWS = 10_000


def build() -> dict:
    plans = pd.read_csv(PLANS)
    plans["tyre_limited"] = plans["optimal_stops"] != plans["min_stops"]
    positive = plans[plans["net_slope_s"] > 0].copy()
    terms = pd.DataFrame({
        "slope": np.log(positive["net_slope_s"]),
        "stint": 2 * np.log(positive["fuel_range_laps"]),
        "pit loss": -np.log(positive["pit_loss_s"]),
    })
    index = terms.sum(axis=1) - np.log(2)
    var = float(index.var())
    shares = {name: float(terms[name].cov(index) / var) for name in terms}
    sds = {name: float(terms[name].std()) for name in terms}
    limited = positive["tyre_limited"].to_numpy()

    def _auc(values: pd.Series) -> float:
        return auc(values[limited].to_numpy(), values[~limited].to_numpy())

    alone = {name: _auc(terms[name]) for name in terms}
    without = {name: _auc(terms.drop(columns=name).sum(axis=1)) for name in terms}

    # Is the difference between the two leave-one-out AUCs, and between the two
    # single-term AUCs, more than resampling noise? Race-seasons are the unit
    # the regime is defined on, so they are what is resampled.
    rng = np.random.default_rng(SEED)
    values = terms.to_numpy()
    cols = list(terms.columns)
    i_slope, i_pit = cols.index("slope"), cols.index("pit loss")
    d_without, d_alone = [], []
    for _ in range(DRAWS):
        pick = rng.integers(0, len(values), len(values))
        v, lab = values[pick], limited[pick]
        if lab.all() or not lab.any():
            continue

        def a(x):
            return auc(x[lab], x[~lab])

        d_without.append(a(v.sum(axis=1) - v[:, i_pit]) - a(v.sum(axis=1) - v[:, i_slope]))
        d_alone.append(a(v[:, i_pit]) - a(v[:, i_slope]))
    diff = {
        "without_slope_minus_without_pit": float(without["slope"] - without["pit loss"]),
        "without_ci": [float(x) for x in np.percentile(np.array(d_without) * -1, [2.5, 97.5])],
        "pit_minus_slope_alone": float(alone["pit loss"] - alone["slope"]),
        "alone_ci": [float(x) for x in np.percentile(d_alone, [2.5, 97.5])],
    }
    return {
        "differences": diff,
        "auc_alone": alone,
        "auc_without": without,
        "n_race_seasons": int(len(plans)),
        "n_positive": int(len(positive)),
        "n_tyre_limited_positive": int(limited.sum()),
        "n_tyre_limited_total": int(plans["tyre_limited"].sum()),
        "shares": shares,
        "sds": sds,
        "index_auc": auc(index[limited].to_numpy(), index[~limited].to_numpy()),
    }


def report(s: dict) -> str:
    lines = [
        "<!-- GENERATED by scripts/run_regime_index.py — do not edit by hand. -->",
        "",
        "# Where the spread of the regime index comes from",
        "",
        f"{s['n_positive']} of {s['n_race_seasons']} race-seasons have a positive net "
        f"slope, and they hold {s['n_tyre_limited_positive']} of the "
        f"{s['n_tyre_limited_total']} tyre-limited ones. On them the index "
        f"log(beta n^2 / 2 pi) separates the regimes at an AUC of {s['index_auc']:.3f}.",
        "",
        "A variance share counts spread wherever it lies, including far from the",
        "boundary where it cannot change a verdict; the leave-one-term-out AUC",
        "counts only what moves races across it. Both are reported.",
        "",
        "| term | share of the index's variance | standard deviation (log units) | AUC alone | index AUC without it |",
        "|---|---|---|---|---|",
    ]
    for name, share in s["shares"].items():
        lines.append(
            f"| {name} | {100 * share:.0f}% | {s['sds'][name]:.2f} | "
            f"{s['auc_alone'][name]:.3f} | {s['auc_without'][name]:.3f} |"
        )
    d = s["differences"]
    lines += [
        "",
        f"Index AUC without the slope minus without pit loss: "
        f"{d['without_slope_minus_without_pit']:+.3f}, 95% interval resampling "
        f"race-seasons [{d['without_ci'][0]:+.3f}, {d['without_ci'][1]:+.3f}]. "
        f"Pit loss alone minus slope alone: {d['pit_minus_slope_alone']:+.3f} "
        f"[{d['alone_ci'][0]:+.3f}, {d['alone_ci'][1]:+.3f}].",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    s = build()
    clean = json.loads(json.dumps(s), parse_float=lambda x: round(float(x), 6))
    OUT_JSON.write_text(json.dumps(clean, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    OUT_MD.write_text(report(s), encoding="utf-8")
    print(report(s))
    return 0


if __name__ == "__main__":
    sys.exit(main())
