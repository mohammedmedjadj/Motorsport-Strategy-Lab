"""The implied ratio, split by the direction of the compound change.

Inverting the closed form at the team's own lap gives

    beta_new / beta_old = (a0 + k) / (W - k),

the age of the tyre at the stop divided by the length of the stint after it. No
fitted slope enters it: it is a ratio of stint lengths read as the wear ratio
that would have made the team's lap optimal. Pooled, it says the first stint is
shorter than the second. Split by direction it can say more:

* below one when the team moves to a harder compound and above one when it moves
  to a softer one: teams act on a compound difference that the fitted slopes do
  not resolve;
* below one in both directions: the explanation lies elsewhere (the first stint
  itself, the option value of a safety car, the undercut).

Reads the committed design-check decisions (lookback five, top five), the same
set as the published implied ratio. The order of the compounds is the race's own
nomination (soft, medium, hard), which within one race is the order of hardness.
Intervals resample races.

Writes ``data/derived/f1/implied_direction_summary.json`` and
``reports/f1/implied_direction.md``.

    python scripts/run_implied_direction.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from src.ingestion.config import F1_DERIVED_DIR, REPORTS_DIR  # noqa: E402

DECISIONS = F1_DERIVED_DIR / "audit_design_checks.csv"
OUT_JSON = F1_DERIVED_DIR / "implied_direction_summary.json"
OUT_MD = REPORTS_DIR / "f1" / "implied_direction.md"
HARDNESS = {"SOFT": 0, "MEDIUM": 1, "HARD": 2}
BOOT_SEED = 20261111
BOOT_DRAWS = 4_000


def decisions() -> pd.DataFrame:
    d = pd.read_csv(DECISIONS)
    d = d[(d["lookback"] == 5) & d["top"]]
    d = d.dropna(subset=["implied_ratio", "fitted_ratio"])
    d = d[d["ratio_class"] != "same compound"].copy()
    harder = d["target"].map(HARDNESS) > d["compound"].map(HARDNESS)
    d["direction"] = np.where(harder, "to harder", "to softer")
    d["race"] = d["season"].astype(str) + "_" + d["circuit"]
    return d


def _race_ci(part: pd.DataFrame, column: str, rng, stat=np.median) -> list[float]:
    groups = {k: g[column].to_numpy() for k, g in part.groupby("race")}
    keys = list(groups)
    reps = []
    for _ in range(BOOT_DRAWS):
        pick = rng.choice(len(keys), len(keys))
        reps.append(stat(np.concatenate([groups[keys[i]] for i in pick])))
    return [float(np.percentile(reps, 2.5)), float(np.percentile(reps, 97.5))]


def summarise(d: pd.DataFrame) -> dict:
    rng = np.random.default_rng(BOOT_SEED)
    out = {"n": int(len(d)), "directions": {}}
    for label, part in d.groupby("direction"):
        below = (part["implied_ratio"] < 1).astype(float)
        out["directions"][label] = {
            "n": int(len(part)),
            "races": int(part["race"].nunique()),
            "implied": float(part["implied_ratio"].median()),
            "implied_ci": _race_ci(part, "implied_ratio", rng),
            "fitted": float(part["fitted_ratio"].median()),
            "fitted_ci": _race_ci(part, "fitted_ratio", rng),
            "share_below_one": float(below.mean()),
            "transitions": {f"{a}-{b}": int(n) for (a, b), n in
                            part.groupby(["compound", "target"]).size().items()},
        }
    # How many of the decisions sit on the side of one that their direction
    # predicts (below one to a harder tyre, above one to a softer tyre).
    expected = np.where(d["direction"] == "to harder", d["implied_ratio"] < 1,
                        d["implied_ratio"] > 1)
    fitted_expected = np.where(d["direction"] == "to harder", d["fitted_ratio"] < 1,
                               d["fitted_ratio"] > 1)
    out["implied_on_expected_side"] = float(np.mean(expected))
    out["fitted_on_expected_side"] = float(np.mean(fitted_expected))
    return out


def report(s: dict) -> str:
    lines = ["# The implied ratio by direction of the compound change", "",
             "Generated by `scripts/run_implied_direction.py`.", "",
             "The implied ratio is (tyre age at the stop) / (length of the next stint): "
             "no fitted slope enters it.", "",
             "| direction | decisions | races | implied ratio | fitted ratio | implied below one |",
             "|---|---|---|---|---|---|"]
    for k, v in s["directions"].items():
        lines.append(
            f"| {k} | {v['n']} | {v['races']} | {v['implied']:.2f} "
            f"[{v['implied_ci'][0]:.2f}, {v['implied_ci'][1]:.2f}] | {v['fitted']:.2f} "
            f"[{v['fitted_ci'][0]:.2f}, {v['fitted_ci'][1]:.2f}] | "
            f"{100 * v['share_below_one']:.0f}% |")
    lines += ["",
              f"The implied ratio sits on the side of one its direction predicts for "
              f"{100 * s['implied_on_expected_side']:.0f}% of the {s['n']} decisions; the "
              f"fitted ratio does for {100 * s['fitted_on_expected_side']:.0f}%.", ""]
    return "\n".join(lines)


def main() -> int:
    s = summarise(decisions())

    def clean(v):
        if isinstance(v, dict):
            return {k: clean(x) for k, x in v.items()}
        if isinstance(v, list):
            return [clean(x) for x in v]
        return round(v, 6) if isinstance(v, float) else v

    OUT_JSON.write_text(json.dumps(clean(s), indent=1, sort_keys=True) + "\n", encoding="utf-8")
    md = report(s)
    OUT_MD.write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
